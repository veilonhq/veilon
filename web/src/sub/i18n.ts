const dicts: Record<Lang, Record<SubKey, string>> = { en, fa };

export function translate(lang: Lang, key: SubKey, vars?: Record<string, string>) {
  let s = dicts[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

export const dictionaries = dicts;
