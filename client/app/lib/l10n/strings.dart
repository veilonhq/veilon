  String t(String key) => (_strings[lang] ?? _strings['en']!)[key] ?? _strings['en']![key] ?? key;

  String f(String key, Map<String, Object> args) {
    var s = t(key);
    args.forEach((k, v) => s = s.replaceAll('{$k}', num(v.toString())));
    return s;
  }

  /// Measurements (speeds, sizes, delays, timers) always use Latin digits
  /// with their Latin units ("0 B/s", "142 ms"): the Persian zero "۰" is a
  /// dot and reads as "no number" next to a Latin unit.
  String metric(String s) => s;

  /// Persian digits when the UI is Persian.
  String num(String s) {
    if (!isFa) return s;
    const fa = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
    final b = StringBuffer();
    for (final r in s.runes) {
      if (r >= 48 && r <= 57) {
        b.write(fa[r - 48]);
      } else if (r == 46) {
        b.write('٫');
      } else {
        b.writeCharCode(r);
      }
    }
    return b.toString();
  }

